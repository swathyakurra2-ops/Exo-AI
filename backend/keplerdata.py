#!/usr/bin/env python3

"""Data Cleaning and Preprocessing Script for Kepler Exoplanet Dataset

This script reads in the 'KeplerExoRaw.csv' file, performs initial cleaning,
and saves a cleaned version. The cleaning workflow includes:
  - Reading the CSV file into a Pandas DataFrame
  - Inspecting the data (head, summary statistics)
  - Renaming columns (if needed) and converting data types
  - Handling missing values (dropping or imputing)
  - Removing duplicate records
  - Saving the cleaned dataset for later analysis

"""

# Import NumPy for numerical operations and pandas for tabular data processing.
import numpy as np
import pandas as pd

# Load the original raw Kepler dataset into a DataFrame.
df= pd.read_csv('KeplerExoRaw.csv')

# Display the first five rows to preview the raw dataset.
df.head()

# Define a function to print a basic overview of the dataset.
def inspect_data(df):
    """Print basic information about the DataFrame."""
    # Show the first five rows of the dataset.
    print("----- Dataset Head -----")
    print(df.head())
    # Show column names, data types, and non-null counts.
    print("\n----- Dataset Info -----")
    print(df.info())
    # Show summary statistics for all columns.
    print("\n----- Summary Statistics -----")
    print(df.describe(include='all'))

# Define a function to standardize the column names.
def clean_column_names(df):
    """    Clean column names: trim extra spaces, convert to lower case, and replace spaces with underscores."""
    # Remove surrounding spaces, convert names to lowercase, and replace spaces with underscores.
    df.columns = [col.strip().lower().replace(' ', '_') for col in df.columns]
    return df

# Define a function to handle missing values in the dataset.
def handle_missing_values(df, threshold=0.5):
    """Handle missing values based on a threshold.
    Drop columns with more than threshold proportion of missing values,
    and impute or drop rows for the rest."""
    # Calculate the fraction of missing values in each column.
    missing_ratio = df.isnull().mean()
    # Identify columns whose missing-value fraction is above the threshold.
    cols_to_drop = missing_ratio[missing_ratio > threshold].index
    if len(cols_to_drop) > 0:
        # Remove columns that contain too many missing values.
        print(f"Dropping columns with > {threshold*100:.0f}% missing values: {list(cols_to_drop)}")
        df = df.drop(columns=cols_to_drop)

    # Fill remaining numeric columns with their median and other columns with their mode.
    for col in df.columns:
        if df[col].dtype in [np.float64, np.int64]:
            # Use the median value to fill missing numeric entries.
            median = df[col].median()
            df[col] = df[col].fillna(median)
        else:
            # Use the most frequent value, or "Unknown" if no mode exists.
            mode = df[col].mode().iloc[0] if not df[col].mode().empty else "Unknown"
            df[col] = df[col].fillna(mode)

    # Optionally: drop any remaining rows with missing values
    # df = df.dropna()
    return df

# Define a function to remove rows that are exact duplicates.
def remove_duplicates(df):
    """Remove duplicate records from the DataFrame."""
    # Record the number of rows before removing duplicates.
    initial_count = len(df)
    # Remove duplicate rows.
    df = df.drop_duplicates()
    # Record the number of rows after removing duplicates.
    final_count = len(df)
    # Report how many duplicate rows were removed.
    print(f"Removed {initial_count - final_count} duplicate rows.")
    return df

# Define a function to convert selected columns to numeric data types when present.
def convert_data_types(df):
    """
    Convert data types if necessary.
    Example: Convert orbit period to numeric if it's not.
    Adjust the columns based on actual dataset schema.
    """
    # Convert orbital_period to numeric; values that cannot be converted become NaN.
    if 'orbital_period' in df.columns:
        df['orbital_period'] = pd.to_numeric(df['orbital_period'], errors='coerce')

    # Convert planet_radius to numeric; values that cannot be converted become NaN.
    if 'planet_radius' in df.columns:
        df['planet_radius'] = pd.to_numeric(df['planet_radius'], errors='coerce')

    # Add any other type conversions based on your exploration
    return df

# Define a function to write the cleaned dataset to a CSV file.
def save_clean_data(df, output_path):
    """Save the cleaned DataFrame to a CSV file."""
    try:
        # Save the DataFrame without writing its row index as an extra column.
        df.to_csv(output_path, index=False)
        print(f"Cleaned data saved to {output_path}")
    except Exception as e:
        # Print the error and re-raise it so the calling code can detect the failure.
        print(f"Error saving clean data: {e}")
        raise

# Standardize the column names before applying the cleaning steps.
df = clean_column_names(df)

# Drop columns with too many missing values and fill missing values in the remaining columns.
df = handle_missing_values(df, threshold=0.5)

# Remove exact duplicate records from the dataset.
df = remove_duplicates(df)

# Convert the selected columns to numeric types when those columns exist.
df = convert_data_types(df)

# Print the cleaned dataset overview and summary statistics.
inspect_data(df)

# Display the first five rows of the cleaned dataset.
df.head()

# Display the number of rows and columns remaining after cleaning.
df.shape

# Save the cleaned dataset as cleankepler.csv for later analysis.
save_clean_data(df, 'cleankepler.csv')
