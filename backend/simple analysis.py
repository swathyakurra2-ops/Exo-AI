# Import pandas for working with tabular data.
import pandas as pd
# Import NumPy for numerical operations.
import numpy as np
# Import Matplotlib for plotting charts.
import matplotlib.pyplot as plt
# Import Seaborn for statistical visualisations.
import seaborn as sns
# Import PCA for reducing many numerical features to fewer components.
from sklearn.decomposition import PCA
# Import StandardScaler to put numerical features on a comparable scale.
from sklearn.preprocessing import StandardScaler

# Apply a white-grid chart style and set the default figure dimensions.
sns.set(style="whitegrid")
plt.rcParams["figure.figsize"] = (10, 6)

# Load the feature-engineered dataset produced by featureEngineer.py.
df = pd.read_csv("data.csv")
# Display the number of rows and columns in the dataset.
df.shape

# Display the first five rows as a quick preview.
df.head()

# Display column names, data types, and non-null counts.
df.info()

# Display summary statistics for numeric and categorical columns.
df.describe(include='all')

"""### Distribution of KOI Disposition

"""

# Plot the number of records in each KOI disposition category, if available.
if "koi_disposition" in df.columns:
    plt.figure()
    sns.countplot(x="koi_disposition", data=df)
    plt.title("Count of KOI Disposition Categories")
    plt.xlabel("KOI Disposition")
    plt.ylabel("Count")
    plt.xticks(rotation=45)
    plt.show()

"""### Trend Over Time: Vet Year Distribution

"""

# Plot how many records belong to each vetting year, if that feature exists.
if "vet_year" in df.columns:
    plt.figure()
    sns.countplot(x="vet_year", data=df)
    plt.title("Distribution of Vet Years")
    plt.xlabel("Year of Vetting")
    plt.ylabel("Number of Records")
    plt.xticks(rotation=45)
    plt.show()

"""### Relationship Between Engineered Features and KOI Disposition

"""

# Compare total positional discrepancy across disposition categories, when both columns exist.
if "total_pos_diff" in df.columns and "koi_disposition" in df.columns:
    plt.figure()
    sns.boxplot(x="koi_disposition", y="total_pos_diff", data=df)
    plt.title("Total Positional Discrepancy by KOI Disposition")
    plt.xlabel("KOI Disposition")
    plt.ylabel("Total Positional Discrepancy")
    plt.xticks(rotation=45)
    plt.show()

"""### Distribution of Engineered Features

"""

# Create two side-by-side plots for the engineered positional-difference features.
fig, axes = plt.subplots(1, 2, figsize=(14, 5))
# Plot the declination positional-difference distribution if the column exists.
if "pos_diff_mdec" in df.columns:
    sns.histplot(df["pos_diff_mdec"], bins=30, kde=True, ax=axes[0])
    axes[0].set_title("Distribution of Positional Difference in Declination")
    axes[0].set_xlabel("Absolute Difference in Declination")
# Plot the combined positional-difference distribution if the column exists.
if "total_pos_diff" in df.columns:
    sns.histplot(df["total_pos_diff"], bins=30, kde=True, ax=axes[1])
    axes[1].set_title("Distribution of Total Positional Discrepancy")
    axes[1].set_xlabel("Total Positional Difference (mdec + msky)")
# Adjust spacing so the two charts fit neatly, then display them.
plt.tight_layout()
plt.show()

"""### Dimensionality Reduction with PCA
### --------------------------

### Select numerical columns from the dataset
"""

# Keep only numeric columns because PCA operates on numerical input.
num_data = df.select_dtypes(include=[np.number])
print("\nNumerical columns used for PCA:")
print(num_data.columns.tolist())

# Remove rows containing missing values in any selected numeric column.
num_data_clean = num_data.dropna()

"""### Standardize the numerical features"""

# Create a scaler that standardizes each feature to mean 0 and standard deviation 1.
scaler = StandardScaler()
# Fit the scaler to the data and transform the features to standardized values.
scaled_data = scaler.fit_transform(num_data_clean)

"""### Apply PCA to reduce the data to 2 components for visualization"""

# Create a PCA model that reduces the numeric features to two components.
pca = PCA(n_components=2)
# Transform the standardized features into the two principal components.
pca_result = pca.fit_transform(scaled_data)
print("Explained variance by principal components:", pca.explained_variance_ratio_)

"""Create a DataFrame for the PCA results"""

# Store the two PCA component values in a DataFrame for plotting.
pca_df = pd.DataFrame(data=pca_result, columns=["PC1", "PC2"])

# Attach the disposition labels for the same rows so points can be coloured by class.
pca_df["koi_disposition"] = df.loc[num_data_clean.index, "koi_disposition"].values

"""pca result"""

# Plot each record in the two-component PCA space, using disposition as the colour.
plt.figure()
sns.scatterplot(x="PC1", y="PC2", hue="koi_disposition", data=pca_df, palette="viridis", alpha=0.7)
plt.title("PCA of Numerical Features (Colored by KOI Disposition)")
plt.xlabel("Principal Component 1")
plt.ylabel("Principal Component 2")
plt.legend(title="KOI Disposition", bbox_to_anchor=(1.05, 1), loc='upper left')
plt.show()

"""Correlaton analysis"""

# Calculate correlations between numeric columns and display them as a heatmap.
plt.figure()
corr_matrix = num_data.corr()
sns.heatmap(corr_matrix, annot=True, cmap="viridis", linewidths=0.5)
plt.title("Correlation Matrix of Numerical Features")
plt.show()
