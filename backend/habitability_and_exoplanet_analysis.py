# Import pandas for loading and manipulating tabular data.
import pandas as pd
# Import Matplotlib and Seaborn for charts and statistical visualisations.
import matplotlib.pyplot as plt
import seaborn as sns
# Import alignment from ctypes; this import is not used in the supplied script.
from ctypes import alignment

# Import tools for splitting data, training a Random Forest, and evaluating predictions.
from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import classification_report, confusion_matrix
# Import LabelEncoder to convert text class labels into numeric labels.
from sklearn.preprocessing import LabelEncoder

# Load the feature-engineered dataset into a DataFrame.
df= pd.read_csv('data.csv')

"""Create habitability flags"""

# Print all available column names for inspection.
print(df.columns.tolist())

# Set the radius flag to 1 when the planet radius is between 0.5 and 1.5 Earth radii.
df['radius_flag'] = df['koi_prad'].between(0.5, 1.5).astype(int)
# Set the temperature flag to 1 when equilibrium temperature is between 200 and 320 K.
df['temp_flag'] = df['koi_teq'].between(200, 320).astype(int)

# Create the combined positional-difference feature only if it is not already present.
if 'total_pos_diff' not in df.columns:
    # List the source columns needed to calculate the positional differences.
    required_cols = ['koi_dicco_mdec', 'koi_dikco_mdec', 'koi_dicco_msky', 'koi_dikco_msky']
    # Continue only when all four source columns are available.
    if all(col in df.columns for col in required_cols):
        # Calculate the absolute difference between the two declination measurements.
        df['pos_diff_mdec'] = (df['koi_dicco_mdec'] - df['koi_dikco_mdec']).abs()
        # Calculate the absolute difference between the two sky-magnitude measurements.
        df['pos_diff_msky'] = (df['koi_dicco_msky'] - df['koi_dikco_msky']).abs()
        # Add both differences to create one combined positional-discrepancy feature.
        df['total_pos_diff'] = df['pos_diff_mdec'] + df['pos_diff_msky']
    else:
        # Identify and report which required source columns are missing.
        missing = [col for col in required_cols if col not in df.columns]
        raise KeyError(f"One or more required positional columns are missing: {missing}")
# Set the positional flag to 1 when the combined discrepancy is below 0.1.
df['pos_flag'] = (df['total_pos_diff'] < 0.1).astype(int)

"""Calculate total habitability score"""

# Add the three binary flags to create a score ranging from 0 to 3.
df['habitability_score'] = df['radius_flag'] + df['temp_flag'] + df['pos_flag']

"""Top 10 most habitable planets"""

# Keep records that meet all three criteria and print up to the first ten.
habitable_df = df[df['habitability_score'] == 3]
print("Top habitability candidates:")
print(habitable_df[['kepoi_name', 'koi_prad', 'koi_teq', 'total_pos_diff', 'habitability_score']].head(10))

"""<b>Score 0: None of the criteria met.</b>

The planet does not fall within the accepted ranges for radius, equilibrium temperature, or positional consistency.

<b>Score 1: Only one criterion met.</b>

The planet meets just one of the conditions (either acceptable radius, temperature, or positional difference), indicating limited habitability potential.

<b>Score 2: Two out of three criteria met.</b>

The planet matches on two of the features, suggesting it could be considered moderately promising in terms of habitability.

<b>Score 3: All three criteria met.</b>

The planet falls within the ideal ranges for radius, equilibrium temperature, and has a low positional discrepancy, making it the strongest candidate based on these parameters.
"""

# Plot how many dataset records have each habitability score.
plt.figure(figsize=(4, 5))
ax = sns.countplot(x='habitability_score', data=df , color= 'purple')
# x_labels = ['Score 0: None of the criteria met.', 'Score 1: Only one criterion met.', 'Score 2: Two out of three criteria met.', 'Score 3: All three criteria met.']
plt.title("Distribution of Habitability Scores")
plt.xlabel("Habitability Scores")
plt.ylabel("Number of Planets")

# Write the count above each bar in the score-distribution chart.
for p in ax.patches:
    height = p.get_height()
    ax.text(p.get_x() + p.get_width() / 2., height + 0.5,
            int(height), ha="center", fontsize=10)
# Adjust chart spacing and display the chart.
plt.tight_layout()
plt.show()

# Plot planet radius against equilibrium temperature, colouring each point by its score.
plt.figure(figsize=(10, 6))
scatter = sns.scatterplot(data=df, x='koi_prad', y='koi_teq', hue='habitability_score',
                          palette='viridis', s=100, edgecolor='k')

# Draw vertical reference lines at the lower and upper radius limits.
plt.axvline(x=0.5, color='red', linestyle='--', label='Radius lower limit')
plt.axvline(x=1.5, color='green', linestyle='--', label='Radius upper limit')
# Draw horizontal reference lines at the lower and upper temperature limits.
plt.axhline(y=200, color='blue', linestyle='--', label='Temperature lower limit')
plt.axhline(y=320, color='purple', linestyle='--', label='Temperature upper limit')

# Add chart labels, legend, and display the plot.
plt.title("Habitability Mapping: Planet Radius vs. Equilibrium Temperature")
plt.xlabel("Planet Radius (Earth radii)")
plt.ylabel("Equilibrium Temperature (K)")
plt.legend(title='Habitability Score', bbox_to_anchor=(1.05, 1), loc='upper left')
plt.show()

# Select the numerical features used as inputs to the Random Forest classifier.
feature_cols = ['koi_prad', 'koi_teq', 'total_pos_diff', 'avg_err_mdec', 'habitability_score']
# Keep only rows that have values for every selected input feature.
X = df[feature_cols].dropna()
# Select the matching disposition labels for the retained rows and convert them to strings.
y = df.loc[X.index, 'koi_disposition'].astype(str)

# Create an encoder that maps the text disposition categories to integer labels.
le = LabelEncoder()
# Fit the encoder to the labels and transform them into numeric class IDs.
y_encoded = le.fit_transform(y)

# Split the features and labels into training and testing subsets.
X_train, X_test, y_train, y_test = train_test_split(X, y_encoded, test_size=0.2, random_state=42)

"""model trainnig"""

# Create a Random Forest classifier with 100 trees and a fixed random seed.
model = RandomForestClassifier(n_estimators=100, random_state=42)
# Train the classifier using the training subset.
model.fit(X_train, y_train)

"""prediction testing/"""

# Predict disposition class IDs for the held-out test features.
y_pred = model.predict(X_test)

"""results"""

# Print precision, recall, F1-score, and support for each disposition class.
print("Classification Report:")
print(classification_report(y_test, y_pred, target_names=le.classes_))

"""Confusion matrix"""

# Calculate how many records fall into each actual-versus-predicted class combination.
conf_matrix = confusion_matrix(y_test, y_pred)
# Display the confusion matrix as a labelled heatmap.
sns.heatmap(conf_matrix, annot=True, fmt='d', xticklabels=le.classes_, yticklabels=le.classes_)
plt.title("Confusion Matrix")
plt.xlabel("Predicted")
plt.ylabel("Actual")
plt.show()

